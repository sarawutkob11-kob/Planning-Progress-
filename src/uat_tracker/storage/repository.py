"""Storage interface. Swap the implementation (phase 2) without touching business logic."""

from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Protocol


class Repository(Protocol):
    def transaction(self) -> AbstractContextManager: ...
    def close(self) -> None: ...

    # import runs
    def start_run(self, *, started_at: str, editor: str, source_path: str,
                  source_mtime: str | None) -> int: ...
    def finish_run(self, run_id: int, *, finished_at: str, result: str, message: str = "",
                   source_sha256: str | None = None, snapshot_path: str | None = None,
                   stats_json: str | None = None) -> None: ...

    # items (one table per sheet); records include '<date>_history' tuples
    def load_items(self, sheet: str) -> dict[str, dict]: ...
    def insert_item(self, sheet: str, item_id: str, fields: dict, meta: dict) -> None: ...
    def update_item(self, sheet: str, item_id: str, fields: dict, meta: dict) -> None: ...
    def set_active(self, sheet: str, item_id: str, active: bool, now: str) -> None: ...

    # sync baseline (raw cell text last read from Excel)
    def load_baseline(self, sheet: str) -> dict[tuple[str, str], str]: ...
    def upsert_baseline(self, sheet: str, item_id: str, field: str, raw: str, now: str) -> None: ...

    # audit log (append-only)
    def append_audit(self, entry: dict) -> int: ...
    def audit_entries(self, item_id: str | None = None) -> list[dict]: ...
    def count_audit(self) -> int: ...

    # review queue
    def load_reviews(self, sheet: str) -> list[dict]: ...
    def insert_review(self, review: dict) -> int: ...
    def set_review_status(self, review_id: int, status: str) -> None: ...
    def open_reviews(self) -> list[dict]: ...

    # data flags
    def load_flags(self, sheet: str) -> dict[tuple[str, str], dict]: ...
    def upsert_flag(self, sheet: str, item_id: str, code: str, detail: str, now: str) -> bool: ...
    def deactivate_flag(self, flag_id: int, now: str) -> None: ...
    def active_flags(self) -> list[dict]: ...

    def count_items(self) -> dict[str, dict[str, int]]: ...

    # ---- Part 2 (alerts)
    def get_item(self, sheet: str, item_id: str) -> dict | None: ...
    def set_field(self, sheet: str, item_id: str, field: str, value, now: str) -> None: ...
    def get_setting(self, key: str) -> str | None: ...
    def set_setting(self, key: str, value: str | None) -> None: ...

    def holidays(self, year: int | None = None) -> dict[str, dict]: ...
    def holiday_years(self) -> set[int]: ...
    def upsert_holiday(self, date_iso: str, name: str, source: str, now: str) -> bool: ...
    def delete_holiday(self, date_iso: str) -> dict | None: ...
    def log_holiday_fetch(self, *, ts: str, year: int, result: str, count: int | None,
                          message: str) -> None: ...
    def holiday_fetches(self, limit: int = 20) -> list[dict]: ...

    def start_job(self, *, job: str, run_date: str, started_at: str, mode: str) -> int: ...
    def finish_job(self, job_id: int, *, finished_at: str, result: str, message: str = "") -> None: ...
    def record_job(self, *, job: str, run_date: str, ts: str, result: str, mode: str | None,
                   message: str) -> int: ...
    def job_runs(self, job: str | None = None, limit: int = 30) -> list[dict]: ...
    def job_dates(self, job: str) -> set[str]: ...
    def job_ok_on(self, job: str, run_date: str) -> bool: ...

    def light_history(self, item_id: str) -> list[dict]: ...
    def latest_lights(self) -> dict[str, dict]: ...
    def insert_light(self, row: dict) -> int: ...

    def insert_email(self, row: dict) -> int: ...
    def email_done(self, rule: str, item_id: str, send_date: str, mode: str) -> bool: ...
    def event_notified(self, rule: str, event_ref: int, mode: str) -> bool: ...
    def email_log(self, *, send_date: str | None = None, item_id: str | None = None,
                  limit: int = 200) -> list[dict]: ...

    def insert_attachment(self, row: dict) -> int: ...
    def attachments(self, sheet: str, item_id: str | None = None) -> list[dict]: ...

    def set_pending(self, sheet: str, item_id: str, field: str, value, now: str, reason: str) -> None: ...
    def pending(self, sheet: str) -> dict[tuple[str, str], dict]: ...
    def clear_pending(self, sheet: str, item_id: str, field: str) -> None: ...

    # ---- Part 3 (sync)
    def upsert_pending(self, sheet: str, item_id: str, field: str, *, value, excel_value: str | None,
                       now: str, reason: str, editor: str, channel: str) -> None: ...
    def all_pending(self) -> list[dict]: ...
    def set_pending_state(self, sheet: str, item_id: str, field: str, *, status: str,
                          attempts: int | None = None, first_failed_at: str | None = None,
                          next_attempt_at: str | None = None, last_error: str | None = None) -> None: ...
    def insert_conflict(self, row: dict) -> int: ...
    def open_conflicts(self, sheet: str | None = None) -> list[dict]: ...
    def get_conflict(self, conflict_id: int) -> dict | None: ...
    def resolve_conflict(self, conflict_id: int, *, resolution: str, resolved_value: str | None,
                         reason: str, resolved_by: str, resolved_at: str) -> None: ...
    def get_review(self, review_id: int) -> dict | None: ...
    def resolve_review(self, review_id: int, *, value: str | None, by: str, at: str) -> None: ...
    def insert_backup(self, row: dict) -> int: ...
    def backups(self, limit: int = 50) -> list[dict]: ...
    def get_backup(self, backup_id: int) -> dict | None: ...
    def log_sync(self, *, ts: str, kind: str, result: str, message: str = "") -> None: ...
    def sync_events(self, limit: int = 30) -> list[dict]: ...
    def last_ok_import(self) -> dict | None: ...
    def insert_app_history(self, sheet: str, item_id: str, field: str, value: str, *, reason: str,
                           root_cause: str | None, now: str) -> None: ...
    def set_import_history(self, sheet: str, item_id: str, field: str, values, now: str) -> None: ...

    # ---- Part 4 (UI)
    def get_contact(self, name_key: str) -> dict | None: ...
    def set_contact(self, name_key: str, name: str, email: str, now: str) -> None: ...
    def all_date_history(self, sheet: str) -> list[dict]: ...
    def max_audit_id(self) -> int: ...
    def search_audit(self, *, text: str | None = None, sheet: str | None = None, editor: str | None = None,
                     date_from: str | None = None, date_to: str | None = None, item_id: str | None = None,
                     limit: int = 2000) -> list[dict]: ...
    def audit_editors(self) -> list[str]: ...
    def get_audit(self, audit_id: int) -> dict | None: ...
    def insert_new_item(self, sheet: str, item_id: str, fields: dict, now: str) -> None: ...
