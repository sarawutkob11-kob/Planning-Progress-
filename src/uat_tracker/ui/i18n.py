_lang = "en"


def set_lang(lang: str) -> None:
    global _lang
    _lang = "th" if lang == "th" else "en"


def get_lang() -> str:
    return _lang


def t(key: str, **kw) -> str:
    en, th = TEXT.get(key, (key, key))
    s = th if _lang == "th" else en
    return s.format(**kw) if kw else s
